"""Generate src/Version.h as YY.MM.DD.N, N counting builds within the day.

Run from build.bat before the compile. The counter lives in a file beside the
build output rather than in the generated header, so the header can be
regenerated from scratch without losing the count, and so a clean of src/
never resets it.
"""
import datetime
import io
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
HEADER = os.path.join(ROOT, 'src', 'Version.h')
COUNTER = os.path.join(ROOT, 'build', 'version_counter.txt')

today = datetime.date.today().strftime('%y.%m.%d')

# The counter file holds "<date> <n>". A date mismatch means this is the
# first build of a new day, so the count restarts at 1.
n = 0
if os.path.exists(COUNTER):
    try:
        parts = io.open(COUNTER, encoding='utf-8').read().split()
        if len(parts) == 2 and parts[0] == today:
            n = int(parts[1])
    except (ValueError, OSError):
        n = 0
n += 1

os.makedirs(os.path.dirname(COUNTER), exist_ok=True)
io.open(COUNTER, 'w', encoding='utf-8').write('%s %d\n' % (today, n))

version = '%s.%d' % (today, n)

# Written only when it actually changes, so an unchanged version does not
# force every translation unit that includes it to rebuild.
text = (
    '#pragma once\n'
    '// GENERATED by tools/genversion.py at build time -- do not edit.\n'
    '// Format: YY.MM.DD.<build of that day>.\n'
    '#define RF2RO_VERSION "%s"\n' % version
)
old = io.open(HEADER, encoding='utf-8').read() if os.path.exists(HEADER) else ''
if old != text:
    io.open(HEADER, 'w', encoding='utf-8', newline='').write(text)

sys.stdout.write('version %s\n' % version)
